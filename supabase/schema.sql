CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  rol TEXT DEFAULT 'vendedor',
  permisos TEXT,
  avatar TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  documento TEXT,
  tipo_documento TEXT DEFAULT 'DNI',
  direccion TEXT,
  email TEXT,
  telefono TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS productos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT,
  precio DOUBLE PRECISION NOT NULL,
  precio_compra DOUBLE PRECISION DEFAULT 0,
  stock INTEGER DEFAULT 0,
  categoria TEXT,
  unidad TEXT DEFAULT 'UND',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  precio_rebaja DOUBLE PRECISION NOT NULL DEFAULT 0,
  precio_pase DOUBLE PRECISION NOT NULL DEFAULT 0,
  codigo_interno TEXT DEFAULT '',
  sku TEXT DEFAULT '',
  codigo_barras TEXT DEFAULT '',
  marca TEXT DEFAULT '',
  unidad_medida TEXT DEFAULT 'UND',
  stock_minimo INTEGER DEFAULT 0,
  stock_maximo INTEGER DEFAULT 0,
  imagen TEXT DEFAULT '',
  activo INTEGER DEFAULT 1,
  igv INTEGER DEFAULT 1,
  ubicacion TEXT DEFAULT '',
  proveedor_principal TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS series (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT UNIQUE NOT NULL,
  serie TEXT NOT NULL,
  ultimo_numero INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS almacenes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  codigo TEXT NOT NULL UNIQUE,
  tipo TEXT DEFAULT 'principal',
  activo INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS comprobantes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL,
  serie TEXT NOT NULL,
  numero INTEGER NOT NULL,
  cliente_id INTEGER NOT NULL REFERENCES clientes(id),
  condicion_pago TEXT DEFAULT 'contado',
  fecha_vencimiento TIMESTAMPTZ,
  comprobante_ref_id INTEGER REFERENCES comprobantes(id),
  motivo_ref TEXT,
  direccion_partida TEXT,
  direccion_llegada TEXT,
  transportista TEXT,
  fecha_traslado TIMESTAMPTZ,
  subtotal DOUBLE PRECISION DEFAULT 0,
  igv DOUBLE PRECISION DEFAULT 0,
  descuento DOUBLE PRECISION DEFAULT 0,
  total DOUBLE PRECISION DEFAULT 0,
  afecta_igv INTEGER DEFAULT 1,
  precios_incluyen_igv INTEGER NOT NULL DEFAULT 0,
  estado TEXT DEFAULT 'emitido',
  fecha TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  fecha_pago TEXT
);

CREATE TABLE IF NOT EXISTS detalle_comprobante (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comprobante_id INTEGER NOT NULL REFERENCES comprobantes(id),
  producto_id INTEGER REFERENCES productos(id),
  descripcion_libre TEXT,
  cantidad DOUBLE PRECISION NOT NULL,
  unidad TEXT DEFAULT 'UND',
  precio_unitario DOUBLE PRECISION DEFAULT 0,
  descuento_item DOUBLE PRECISION DEFAULT 0,
  subtotal DOUBLE PRECISION DEFAULT 0,
  tipo_precio TEXT NOT NULL DEFAULT 'unidad'
);

CREATE TABLE IF NOT EXISTS pagos_comprobante (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comprobante_id INTEGER NOT NULL REFERENCES comprobantes(id),
  monto DOUBLE PRECISION NOT NULL CHECK (monto > 0),
  fecha_pago TEXT NOT NULL,
  metodo_pago TEXT NOT NULL,
  referencia TEXT,
  usuario_id INTEGER REFERENCES usuarios(id),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS kardex_movimientos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INTEGER NOT NULL REFERENCES productos(id),
  almacen_id INTEGER NOT NULL REFERENCES almacenes(id),
  tipo TEXT NOT NULL,
  cantidad INTEGER NOT NULL,
  costo_unitario DOUBLE PRECISION DEFAULT 0,
  stock_anterior INTEGER NOT NULL,
  stock_posterior INTEGER NOT NULL,
  documento_relacionado TEXT,
  observacion TEXT,
  usuario_id INTEGER REFERENCES usuarios(id),
  fecha TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS documentos_compra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL,
  orden_compra TEXT,
  serie TEXT,
  numero TEXT,
  condicion_pago TEXT,
  plazo_pago TEXT,
  fecha_factura TEXT,
  fecha_ingreso TEXT,
  fecha_pago TEXT,
  porcentaje DOUBLE PRECISION,
  estado TEXT DEFAULT 'pendiente',
  proveedor_documento TEXT NOT NULL,
  proveedor_razon_social TEXT NOT NULL,
  proveedor_direccion TEXT,
  moneda TEXT DEFAULT 'PEN',
  tipo_cambio DOUBLE PRECISION,
  archivo_nombre TEXT,
  archivo_ruta TEXT,
  archivo_mime TEXT,
  factura_archivo_nombre TEXT,
  factura_archivo_ruta TEXT,
  factura_archivo_mime TEXT,
  guia_archivo_nombre TEXT,
  guia_archivo_ruta TEXT,
  guia_archivo_mime TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS detalle_documento_compra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento_compra_id INTEGER NOT NULL REFERENCES documentos_compra(id),
  producto_id INTEGER NOT NULL REFERENCES productos(id),
  cantidad INTEGER NOT NULL,
  costo_unitario DOUBLE PRECISION NOT NULL DEFAULT 0,
  almacen_id INTEGER NOT NULL REFERENCES almacenes(id)
);

CREATE TABLE IF NOT EXISTS pagos_documento_compra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento_compra_id INTEGER NOT NULL REFERENCES documentos_compra(id),
  monto DOUBLE PRECISION NOT NULL CHECK (monto > 0),
  fecha_pago TEXT NOT NULL,
  metodo_pago TEXT NOT NULL,
  referencia TEXT,
  usuario_id INTEGER REFERENCES usuarios(id),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS proveedores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento TEXT NOT NULL,
  razon_social TEXT NOT NULL,
  direccion TEXT,
  telefono TEXT,
  email TEXT,
  activo INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tipo_cambio_diario (
  fecha TEXT PRIMARY KEY,
  compra DOUBLE PRECISION NOT NULL,
  venta DOUBLE PRECISION NOT NULL,
  fuente TEXT NOT NULL,
  actualizado_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS proveedores_documento_ci_unique
  ON proveedores (lower(documento));
CREATE INDEX IF NOT EXISTS comprobantes_cliente_fecha_idx
  ON comprobantes (cliente_id, fecha DESC);
CREATE INDEX IF NOT EXISTS detalle_comprobante_documento_idx
  ON detalle_comprobante (comprobante_id);
CREATE INDEX IF NOT EXISTS detalle_documento_compra_documento_idx
  ON detalle_documento_compra (documento_compra_id);
CREATE INDEX IF NOT EXISTS kardex_producto_fecha_idx
  ON kardex_movimientos (producto_id, fecha DESC);